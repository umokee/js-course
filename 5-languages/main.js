const language = "en";

switch (language) {
  case "en":
    console.log("Good day!");
    break;
  case "ru":
    console.log("Добрый день!");
    break;
  case "de":
    console.log("Gutten tag!");
    break;
  case "fr":
    console.log("Bonne journée!");
    break;
  case "pl":
    console.log("Dzień dobry!");
    break;
  default:
    console.log("Language doesn't support");
}
